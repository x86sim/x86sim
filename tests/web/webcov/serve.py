#!/usr/bin/env python3
# webcov: the web-platform coverage suite's host server (stdlib only; runs on Linux and on the Mac's Python 3.9).
# Serves tests/web/webcov/ (pages, checks, media) with the headers the checks need and collects the results:
#   every response    COOP same-origin + COEP require-corp (crossOriginIsolated -> SharedArrayBuffer, WASM threads)
#                     + CORP cross-origin; Service-Worker-Allowed: /
#   POST /r/<run>     one JSON event per request ({"ev": "start"|"result"|"done"|"log", ...}) appended to
#                     OUT/<run>.jsonl; GET /r/<run> answers {"done": [ids], "started": id|null, "finished": bool}
#                     (the harness resumes after a WebContent crash: the started-but-unfinished check is a CRASH)
#   /ws               WebSocket echo (RFC 6455, text + binary)            /sse   EventSource: 3 events then close
#   /cors/*           Access-Control-Allow-Origin for the page's origin; the harness fetches it as http://localhost:PORT
#                     (another origin than 127.0.0.1:PORT)                 /slow?ms=N   delayed body (streams)
#   /chunked          a chunked body of 5 parts (ReadableStream reads)     /echo   POST body back
#   /cookie           Set-Cookie wc_srv=1; GET /cookies answers the request's Cookie header
#   /hls/...          media/hls (generated by gen-media.sh) with the HLS MIME types
# Usage: serve.py --port 7420 --root DIR --out DIR [--media DIR]
import argparse, base64, hashlib, json, os, socket, struct, sys, threading, time
from http.server import ThreadingHTTPServer, BaseHTTPRequestHandler
from urllib.parse import urlparse, parse_qs

MIME = {'.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css',
	'.json': 'application/json', '.wasm': 'application/wasm', '.svg': 'image/svg+xml', '.png': 'image/png',
	'.mp4': 'video/mp4', '.m4a': 'audio/mp4', '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.webm': 'video/webm',
	'.caf': 'audio/x-caf', '.m3u8': 'application/vnd.apple.mpegurl', '.ts': 'video/mp2t', '.m4s': 'video/iso.segment',
	'.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf', '.otf': 'font/otf', '.txt': 'text/plain',
	'.webmanifest': 'application/manifest+json', '.wav': 'audio/wav', '.flac': 'audio/flac', '.mov': 'video/quicktime'}
lock = threading.Lock()

class H(BaseHTTPRequestHandler):
	protocol_version = 'HTTP/1.1'
	def log_message(self, fmt, *a):
		if A.verbose: sys.stderr.write('webcov-serve: ' + fmt % a + '\n')
	def hdrs(self, code, ctype=None, length=None, extra=()):
		self.send_response(code)
		if ctype: self.send_header('Content-Type', ctype)
		if length is not None: self.send_header('Content-Length', str(length))
		self.send_header('Cross-Origin-Opener-Policy', 'same-origin')
		self.send_header('Cross-Origin-Embedder-Policy', 'require-corp')
		self.send_header('Cross-Origin-Resource-Policy', 'cross-origin')
		self.send_header('Service-Worker-Allowed', '/')
		self.send_header('Cache-Control', 'no-store')
		for k, v in extra: self.send_header(k, v)
		self.end_headers()
	def body(self, code, data, ctype='text/plain', extra=()):
		if isinstance(data, str): data = data.encode()
		self.hdrs(code, ctype, len(data), extra); self.wfile.write(data)
	def cors(self):
		o = self.headers.get('Origin')
		return [('Access-Control-Allow-Origin', o or '*'), ('Access-Control-Allow-Credentials', 'true'),
			('Access-Control-Allow-Headers', 'X-Webcov, Content-Type'), ('Access-Control-Allow-Methods', 'GET, POST, PUT'),
			('Access-Control-Expose-Headers', 'X-Webcov-Echo'), ('Vary', 'Origin')]
	def do_OPTIONS(self):
		self.body(204, b'', extra=self.cors())
	def do_POST(self):
		u = urlparse(self.path); n = int(self.headers.get('Content-Length') or 0); data = self.rfile.read(n) if n else b''
		if u.path.startswith('/r/'):
			run = os.path.basename(u.path[3:]) or 'run'
			try:
				evs = json.loads(data); evs = evs if isinstance(evs, list) else [evs]
			except Exception as e:
				return self.body(400, 'bad json: %s' % e)
			with lock, open(os.path.join(A.out, run + '.jsonl'), 'a') as f:
				for ev in evs:
					ev['t'] = time.time(); f.write(json.dumps(ev) + '\n')
			return self.body(200, 'ok', extra=self.cors())
		if u.path.startswith('/echo') or u.path.startswith('/cors/echo'):
			return self.body(200, data, self.headers.get('Content-Type') or 'application/octet-stream',
				extra=self.cors() + [('X-Webcov-Echo', str(len(data)))])
		self.body(404, 'no')
	def do_PUT(self): self.do_POST()
	def do_GET(self):
		u = urlparse(self.path); q = parse_qs(u.query); p = u.path
		if p.startswith('/r/'):
			run = os.path.basename(p[3:]); done, started, fin = [], None, False
			try:
				for line in open(os.path.join(A.out, run + '.jsonl')):
					ev = json.loads(line)
					if ev.get('ev') == 'start': started = ev['id']
					elif ev.get('ev') == 'result':
						done.append(ev['id'])
						if started == ev['id']: started = None
					elif ev.get('ev') == 'done': fin = True
			except FileNotFoundError: pass
			return self.body(200, json.dumps({'done': done, 'started': started, 'finished': fin}), 'application/json')
		if p == '/ws': return self.websocket()
		if p == '/sse':
			self.hdrs(200, 'text/event-stream', extra=[('Connection', 'close')])
			for i in range(3):
				self.wfile.write(('id: %d\nevent: tick\ndata: {"n": %d}\n\n' % (i, i)).encode()); self.wfile.flush(); time.sleep(0.1)
			self.close_connection = True; return
		if p.startswith('/cors/'):
			if p == '/cors/data': return self.body(200, '{"cors": true}', 'application/json', extra=self.cors())
			if p == '/cors/nocors': return self.body(200, '{"cors": false}', 'application/json')
			if p == '/cors/cookie': return self.body(200, json.dumps({'cookie': self.headers.get('Cookie') or ''}), 'application/json', extra=self.cors())
		if p == '/slow':
			time.sleep(int(q.get('ms', ['500'])[0]) / 1000); return self.body(200, 'slow', extra=self.cors())
		if p == '/chunked':
			self.hdrs(200, 'text/plain', extra=[('Transfer-Encoding', 'chunked')] + self.cors())
			for i in range(5):
				c = ('part%d;' % i).encode(); self.wfile.write(b'%x\r\n%s\r\n' % (len(c), c)); self.wfile.flush(); time.sleep(0.15)
			self.wfile.write(b'0\r\n\r\n'); return
		if p == '/cookie':
			return self.body(200, 'set', extra=[('Set-Cookie', 'wc_srv=1; Path=/; SameSite=Lax'), ('Set-Cookie', 'wc_http=1; Path=/; HttpOnly')])
		if p == '/cookies': return self.body(200, self.headers.get('Cookie') or '', extra=self.cors())
		if p == '/headers': return self.body(200, json.dumps(dict(self.headers.items())), 'application/json', extra=self.cors())
		if p == '/gzip':
			import gzip
			return self.body(200, gzip.compress(b'webcov-gzip ' * 100), 'text/plain', extra=[('Content-Encoding', 'gzip')])
		if p == '/': p = '/index.html'
		# files: the suite's root, then the generated media dir (served under /media/)
		base, rel = A.root, p.lstrip('/')
		if rel.startswith('media/') and A.media: base, rel = A.media, rel[6:]
		fp = os.path.realpath(os.path.join(base, rel))
		if not fp.startswith(os.path.realpath(base)) or not os.path.isfile(fp): return self.body(404, 'not found: ' + p)
		ctype = MIME.get(os.path.splitext(fp)[1], 'application/octet-stream')
		size = os.path.getsize(fp); rng = self.headers.get('Range')
		with open(fp, 'rb') as f:
			if rng and rng.startswith('bytes='):   # media elements read with Range
				a, _, b = rng[6:].partition('-'); a = int(a or 0); b = int(b) if b else size - 1; b = min(b, size - 1)
				f.seek(a); data = f.read(b - a + 1)
				self.hdrs(206, ctype, len(data), [('Content-Range', 'bytes %d-%d/%d' % (a, b, size)), ('Accept-Ranges', 'bytes')])
				self.wfile.write(data); return
			data = f.read()
		self.body(200, data, ctype, extra=[('Accept-Ranges', 'bytes')])
	def do_HEAD(self): self.do_GET()

	def websocket(self):
		key = self.headers.get('Sec-WebSocket-Key')
		if not key: return self.body(400, 'not a websocket')
		acc = base64.b64encode(hashlib.sha1((key + '258EAFA5-E914-47DA-95CA-C5AB0DC85B11').encode()).digest()).decode()
		self.send_response(101); self.send_header('Upgrade', 'websocket'); self.send_header('Connection', 'Upgrade')
		self.send_header('Sec-WebSocket-Accept', acc); self.end_headers()
		r, w = self.rfile, self.wfile
		def recv(n):
			b = r.read(n)
			if len(b) < n: raise EOFError
			return b
		try:
			while True:
				h = recv(2); op = h[0] & 15; ln = h[1] & 127
				if ln == 126: ln = struct.unpack('>H', recv(2))[0]
				elif ln == 127: ln = struct.unpack('>Q', recv(8))[0]
				mask = recv(4) if h[1] & 128 else b'\0\0\0\0'
				d = bytes(c ^ mask[i % 4] for i, c in enumerate(recv(ln)))
				if op == 8: w.write(b'\x88\x00'); w.flush(); break
				if op == 9: op = 10
				hdr = bytes([0x80 | op]) + (bytes([len(d)]) if len(d) < 126 else
					(b'\x7e' + struct.pack('>H', len(d)) if len(d) < 65536 else b'\x7f' + struct.pack('>Q', len(d))))
				w.write(hdr + d); w.flush()
		except (EOFError, ConnectionError, OSError): pass
		self.close_connection = True

class S(ThreadingHTTPServer):
	daemon_threads = True
	allow_reuse_address = True
	def server_bind(self):
		self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1); super().server_bind()

if __name__ == '__main__':
	ap = argparse.ArgumentParser()
	ap.add_argument('--port', type=int, default=7420); ap.add_argument('--bind', default='127.0.0.1')
	ap.add_argument('--root', default=os.path.dirname(os.path.abspath(__file__)))
	ap.add_argument('--out', required=True); ap.add_argument('--media'); ap.add_argument('-v', '--verbose', action='store_true')
	A = ap.parse_args(); os.makedirs(A.out, exist_ok=True)
	srv = S((A.bind, A.port), H)
	print('webcov-serve: http://%s:%d/ out %s' % (A.bind, A.port, A.out), flush=True)
	srv.serve_forever()
